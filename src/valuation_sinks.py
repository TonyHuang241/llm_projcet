"""研报 CAR 与 DAG 指标里“目标节点”的口径。

现行口径：TARGET —— 只认名称恰好等于“投资评级”的那一个概念（精确相等，不做包含匹配；
买入评级、目标评级、目标价、估值等一律不算），也不要求它是汇点。
在 790 篇上的预期结果：607 篇图中有它（其中 605 篇是汇点、2 篇还有出边），183 篇没有。

RULES_BROAD / group()：上一版宽口径（“估值相关汇点”，按 790 篇研报的 11660 个汇点名称逐个看过后定的 9 组正则规则），
现在不用，只留作对照。每条规则：(分组, 命中的正则, 排除的正则或 None)，按顺序匹配，命中第一条即归入该组；
都不命中则不算估值相关。当时在 790 篇上的结果：197 个名称、1201 个汇点、695 篇研报至少有 1 个。"""
import re

TARGET = '投资评级'  # 现行口径

# 上一版宽口径，现在不用
RULES_BROAD = [
    ('评级', r'评级', r'信用评级|主体评级|债项评级|ESG评级|评级机构'),
    ('目标价', r'目标价|目标股价|目标市值|目标估值|目标P[EB]', None),
    ('估值', r'估值', r'收购估值'),
    ('估值倍数', r'市盈率|市净率|市销率|PEG|P/E|P/B|EV/EBITDA|(?<![A-Za-z])P[EB](?![A-Za-z/])', r'需求|产能|供需|价格|产量|出口|进口|投资'),
    ('股价市值', r'股价|每股价格|市值', r'市值管理|持仓市值'),
    ('投资价值', r'投资价值|配置价值|企业价值|内在价值|合理价值|每股价值|公司价值|价值重估|重估机会|底仓价值|权益价值|股东价值', r'黄金价值重估'),
    ('涨跌空间与收益', r'上涨空间|上行空间|下行空间|安全边际|戴维斯|超额收益|相对收益|绝对收益|资本利得|股票吸引力|投资性价比|公司市场表现|板块行情|行情走势|行情表现|α行情', r'PTA超额收益'),
    ('股息率', r'股息率|股息溢价|股息吸引力|股息配置', None),
    ('折现率', r'WACC', None),
]


def group(name):
    """上一版宽口径（现在不用）：汇点名称 -> 分组名；不是估值相关的返回空串。"""
    for g, inc, exc in RULES_BROAD:
        if re.search(inc, name) and not (exc and re.search(exc, name)):
            return g
    return ''
