# 直接连到“公司估值”的科目
TO_ROOT = ['归母净利润', '自由现金流', 'ROE', '分红', 'EBITDA', MULTIPLE]

GROWTH_RE = re.compile(r'(同比|环比)?(增速|增长|增幅|增长率)$')


def _key(s):
    s = unicodedata.normalize('NFKC', str(s or ''))
    return re.sub(r'[\s\-_·/、，,()“”"\']', '', s).casefold()


ALIAS = {}
for _name, (_aliases, _) in ITEMS.items():
    for _a in [_name, *_aliases.split()]:
        ALIAS.setdefault(_key(_a), _name)

PRESET_EDGES = [*EDGES, *[(n, ROOT, 1) for n in TO_ROOT]]
DEFS = {name: d for name, (_, d) in ITEMS.items()}


def match(name):
    """名称对应的预置节点（公司估值、估值倍数或会计科目），不是预置节点返回 None。"""
    k = _key(name)
    if k in ALIAS:
        return ALIAS[k]
    k = _key(GROWTH_RE.sub('', unicodedata.normalize('NFKC', str(name or '')).strip()))
    return ALIAS.get(k) if len(k) >= 2 else None


def accounting_list():
    """给大模型看的会计层清单：每行“规范名（别名）”。"""
    return '\n'.join(f'{n}（{"、".join(a.split()[:6])}）' if a else n for n, (a, _) in ITEMS.items() if n != ROOT)


def _check():
    names = set(ITEMS)
    for u, v, s in PRESET_EDGES:
        assert u in names and v in names and s in (1, -1), (u, v, s)
    import networkx as nx
    g = nx.DiGraph([(u, v) for u, v, _ in PRESET_EDGES])
    assert nx.is_directed_acyclic_graph(g), '预置关系有环'
    assert set(g) == names and nx.ancestors(g, ROOT) == names - {ROOT}, '有科目连不到公司估值'


_check()
